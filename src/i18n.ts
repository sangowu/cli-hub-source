export function resolveLanguage(preference: LanguagePreference): ResolvedLanguage {
  if (preference !== "system") {
    return preference;
  }

  const systemLanguage = typeof navigator === "undefined" ? "en" : navigator.language;
  return systemLanguage.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function resolveColorMode(
  preference: ColorModePreference,
  systemPrefersDark: boolean,
): ResolvedColorMode {
  if (preference !== "system") {
    return preference;
  }

  return systemPrefersDark ? "dark" : "light";
}
